    let s = fs.readFileSync(f, "utf8"); const crlf = s.includes("\r\n"); s = s.replace(/\r\n/g, "\n")
    const a = s.indexOf(START), b = s.indexOf(END)
    if (a >= 0 && b > a) s = s.slice(0, a) + s.slice(b + END.length + 1)
    const block = [START, ...Object.entries(K).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v[idx])},`), END].join("\n") + "\n"
    const end = s.lastIndexOf("\n}")
    s = s.slice(0, end + 1) + block + s.slice(end + 1)
