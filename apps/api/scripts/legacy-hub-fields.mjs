// Generates src/lib/legacyHubFields.ts: the fields (scalars and relations) every model had in the Prisma schema of
// the oldest published hub that pulls with sync schema 2 (v1.0.49; 1.0.50 and 1.0.51 add only StaffUser.roleVersion).
// Those hubs insert pulled rows verbatim, so a column they lack fails the whole entity.
//   git show v1.0.49:apps/api/prisma/schema.prisma > legacy.prisma && node scripts/legacy-hub-fields.mjs legacy.prisma
import { readFileSync, writeFileSync } from "node:fs"
const src = readFileSync(process.argv[2], "utf8")
const models = {}
const scalar = new Set(["String", "Int", "Float", "Boolean", "DateTime", "Json", "Decimal", "BigInt", "Bytes"])
const names = new Set([...src.matchAll(/^model (\w+) \{/gm)].map((m) => m[1]))
for (const m of src.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) {
  const fields = {}
  for (const line of m[2].split("\n")) {
    const t = line.trim()
    if (!t || t.startsWith("//") || t.startsWith("@@")) continue
    const [name, type] = t.split(/\s+/)
    if (!name || !type) continue
    const base = type.replace(/[?\[\]]/g, "")
    fields[name] = names.has(base) ? base : null
    if (!names.has(base) && !scalar.has(base) && !/^[A-Z]/.test(base)) throw new Error(`unexpected type ${type} in ${m[1]}.${name}`)
  }
  models[m[1]] = fields
}
const out = `// GENERATED by scripts/legacy-hub-fields.mjs from the v1.0.49 Prisma schema — do not edit by hand.
// Field name -> related model (relations) or null (columns), per model.
export const LEGACY_HUB_FIELDS: Record<string, Record<string, string | null>> = ${JSON.stringify(models, null, 2)}
`
writeFileSync(new URL("../src/lib/legacyHubFields.ts", import.meta.url), out)
console.log(`models ${Object.keys(models).length}`)
